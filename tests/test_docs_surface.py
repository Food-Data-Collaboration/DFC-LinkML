def test_conformance_report_exists():
    """Phase 4 acceptance: the fixtures x connectors matrix, auto-updated.

    Generated by scripts/generate_conformance_report.py and wired into the
    reference step, so --check covers it and it cannot drift from the suite.
    """
    page = DOCS / 'conformance.md'
    assert page.is_file(), 'docs/conformance.md is missing'
    text = page.read_text(encoding='utf-8')
    assert 'Do not edit' in text, 'the page should say it is generated'
    # Every fixture and every connector has to appear, or the table silently
    # omits coverage rather than reporting it missing.
    fixtures = sorted((REPO / 'tests' / 'conformance' / 'valid').glob('*.jsonld'))
    assert fixtures, 'no conformance fixtures found'
    for fixture in fixtures:
        assert f'## {fixture.stem}' in text, f'no section for {fixture.stem}'
    for display in ('TypeScript', 'Ruby', 'PHP'):
        assert display in text, f'{display} missing from the conformance report'


def test_conformance_report_covers_every_fixture_and_connector():
    """The report must have a cell for every fixture/connector/property pair.

    Counted rather than eyeballed: a table that silently drops a row reads as
    coverage it does not have.
    """
    text = (DOCS / 'conformance.md').read_text(encoding='utf-8')
    fixtures = sorted((REPO / 'tests' / 'conformance' / 'valid').glob('*.jsonld'))
    # Two properties (import, round-trip) per connector per fixture.
    expected_rows = len(fixtures) * 3
    per_fixture_rows = [
        ln for ln in text.splitlines()
        if ln.startswith('| ') and ('npx jsr add' in ln or 'gem install' in ln
                                    or 'composer require' in ln)
        and not ln.startswith('| Connector')
        and 'Install |' not in ln
    ]
    # Fixture tables: 3 connectors each, plus 3 summary rows.
    assert len(per_fixture_rows) == expected_rows + 3, (
        f'expected {expected_rows} fixture cells + 3 summary rows, '
        f'found {len(per_fixture_rows)}'
    )


