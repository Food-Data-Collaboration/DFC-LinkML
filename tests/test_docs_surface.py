def test_facade_counts_match_schema_class_count():
    """Every DFC class should have a factory in TS and PHP, and none in Ruby."""
    classes = yaml.safe_load(
        (REPO / 'src' / 'dfc_business_linkml_v2_0.yaml').read_text(encoding='utf-8')
    )['classes']
    n = len(classes)
    ts_factories = len(parse_ts(TS_CONNECTOR)[1])
    php_factories = len(parse_php(REPO / 'php-connector' / 'src' / 'Connector.php')[1])
    assert ts_factories == n, f'TS has {ts_factories} factories for {n} classes'
    assert php_factories == n, f'PHP has {php_factories} factories for {n} classes'


