def test_api_pages_match_the_parsers():
    """Every method the parsers find must be on the page, and vice versa."""
    cases = [
        ('typescript', parse_ts(TS_CONNECTOR)[0]),
        ('ruby', parse_ruby(REPO / 'ruby-gem' / 'lib' / 'core' / 'connector.rb')[0]),
        ('php', parse_php(REPO / 'php-connector' / 'src' / 'Connector.php')[0]),
    ]
    for slug, methods in cases:
        text = read(API / f'{slug}.md')
        for m in methods:
            assert f'`{m}()`' in text, f'{slug}.md omits parsed method {m}'


def test_ts_parser_finds_async_and_accessors():
    """Regression: the first parser dropped both, understating the API.

    TypeScript's connector has 3 async methods and 6 `get` accessors. If
    either count collapses to zero, the parser has regressed.
    """
    methods, _factories, accessors = parse_ts(TS_CONNECTOR)
    async_methods = [m for m in methods if m.startswith(('getContext', 'load'))]
    assert len(async_methods) >= 3, f'async methods missing: {methods}'
    assert len(accessors) >= 6, f'get accessors missing: {accessors}'
    assert 'contextUrl' in accessors
    for acc in ('facet', 'measure', 'product_type'):
        assert acc in accessors, f'{acc} accessor missing'


def test_ruby_parser_finds_its_real_accessors():
    """Ruby exposes some state via attr_reader and some via def.

    `facet`/`measure`/`product_type` are defs (they lazy-load), so they land
    in the method list. Only the plain state is attr_reader.
    """
    methods, accessors = parse_ruby(
        REPO / 'ruby-gem' / 'lib' / 'core' / 'connector.rb'
    )
    for acc in ('ontology_version', 'taxonomy_version', 'vocab_loader'):
        assert acc in accessors, f'ruby attr_reader {acc} missing'
    for meth in ('facet', 'measure', 'product_type'):
        assert meth in methods, f'ruby def {meth} missing'


def test_operations_table_covers_the_parsed_surface():
    """Every operation named for a language must be callable there.

    Accessors count as callable: `contextUrl` is a TS getter, not a method,
    so the availability set has to include accessors or this reports a false
    failure.
    """
    ts_methods, _f, ts_acc = parse_ts(TS_CONNECTOR)
    rb_methods, rb_acc = parse_ruby(
        REPO / 'ruby-gem' / 'lib' / 'core' / 'connector.rb'
    )
    php_methods, _pf, php_acc = parse_php(
        REPO / 'php-connector' / 'src' / 'Connector.php'
    )
    available = {
        1: set(ts_methods) | set(ts_acc),
        2: set(rb_methods) | set(rb_acc),
        3: set(php_methods) | set(php_acc),
    }
    for op in OPERATIONS:
        for col, names in available.items():
            bare = op[col][0]
            if bare is None:
                continue
            assert bare in names, (
                f'operations table claims {op[0]!r} exists as {bare!r} '
                f'but the connector has no such member'
            )


