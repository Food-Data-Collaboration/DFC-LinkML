def test_build_a_catalog_uses_the_real_price_shape():
    """Regression guard.

    The first draft of this guide hung a Price off SuppliedProduct. There is
    no such slot: has_price lives on Offer, OrderLine, PaymentMethod, and
    Transaction. TypeScript accepted `carrots.price = ...` without complaint
    and dropped the value on export, so the example looked fine and produced
    no price at all.
    """
    text = read(GUIDES / 'build-a-catalog.md')
    assert 'createOffer' in text, 'the guide must build an Offer'
    assert 'createCatalogItem' in text, 'the bridge node is part of the shape'
    # It must warn against the mistake explicitly, since the connector
    # accepts the bad assignment without complaint.
    assert 'does not raise' in text, (
        'the guide should warn that a non-existent slot is silently ignored'
    )
    assert 'has_price' in text, 'the guide should say where has_price lives'


